"""
Shared Scan Result data model for Project SETU.

Defines dataclasses for the canonical shared result format JSON used
across pipeline, API, and frontend.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass, field
import json
from typing import Any, Dict, List, Literal, Optional, Sequence, Union

DEFAULT_DISCLAIMER: str = (
    "SETU does not assess safety. Flagged readings are for engineer review."
)


@dataclass
class Verdict:
    """Scan quality verdict tier and diagnostic reasons."""

    level: Literal["usable", "weak", "failed"] = "usable"
    reasons: List[str] = field(default_factory=list)


@dataclass
class Location:
    """Geographic coordinate of video recording."""

    lat: float = 0.0
    lon: float = 0.0


@dataclass
class VideoInfo:
    """Video container metadata and stream characteristics."""

    filename: str = ""
    fps: float = 0.0
    duration_s: float = 0.0
    width: int = 0
    height: int = 0
    frame_count: int = 0


@dataclass
class SegmentationInfo:
    """Target and background segmentation provenance and persistence metrics."""

    target_prompt: str = "concrete pillar"
    background_prompt: str = "building"
    target_source: str = "sam"
    background_source: str = "sam"
    target_persistence: float = 1.0
    background_persistence: Optional[float] = 1.0
    warnings: List[str] = field(default_factory=list)


@dataclass
class MeasurementPeak:
    """Detected dominant vibration frequency peak with power and SNR."""

    frequency_hz: float = 0.0
    relative_power: float = 0.0
    snr_db: float = 0.0


@dataclass
class PSDData:
    """Welch Power Spectral Density frequencies and powers (<= 300 points between 0 and 30 Hz)."""

    freq_hz: List[float] = field(default_factory=list)
    power: List[float] = field(default_factory=list)


@dataclass
class MeasurementInfo:
    """Subpixel vibration telemetry extracted from structural displacement."""

    units: str = "px"
    scale: Optional[float] = None
    dominant_frequency_hz: Optional[float] = None
    frequency_ci_hz: Optional[List[float]] = None
    peaks: List[MeasurementPeak] = field(default_factory=list)
    psd: Optional[PSDData] = None
    background_residual_px: float = 0.0


@dataclass
class QualityGateInfo:
    """Visual safety quality gate results evaluating structural suitability."""

    is_structural_element: bool = True
    has_static_background: bool = True
    appears_stable: bool = True
    issues: List[str] = field(default_factory=list)


@dataclass
class AssessmentInfo:
    """Safety screening anomaly assessment produced by local rules or Muse Spark."""

    severity: str = "none"
    reasons: List[str] = field(default_factory=list)
    expected_range_hz: Optional[List[float]] = None
    confidence: str = "low"
    recommended_action: str = ""
    assessor: str = "local_rules"


@dataclass
class InterpretationInfo:
    """Infrastructure synthesis uniting OSM bridge metadata, quality gate, and assessment."""

    bridge: Optional[Dict[str, Any]] = None
    bridge_warning: Optional[str] = "No mapped bridge within 150 m"
    quality_gate: QualityGateInfo = field(default_factory=QualityGateInfo)
    assessment: AssessmentInfo = field(default_factory=AssessmentInfo)


@dataclass
class OutputsInfo:
    """Output artifact filenames generated by the screening pipeline."""

    magnified_video: Optional[str] = None
    spectrum_plot: Optional[str] = None
    displacement_plot: Optional[str] = None


@dataclass
class CostsUSD:
    """Breakdown of API cloud inference costs incurred during processing."""

    sam: float = 0.0
    muse_spark: float = 0.0
    total: float = 0.0


@dataclass
class ScanResult:
    """Canonical scan result representation for Project SETU."""

    schema_version: str = "1.0"
    scan_id: str = ""
    is_demo: bool = False
    created_at: str = ""
    status: Literal["queued", "running", "complete", "error"] = "complete"
    verdict: Verdict = field(default_factory=Verdict)
    location: Location = field(default_factory=Location)
    video: VideoInfo = field(default_factory=VideoInfo)
    segmentation: SegmentationInfo = field(default_factory=SegmentationInfo)
    measurement: MeasurementInfo = field(default_factory=MeasurementInfo)
    interpretation: InterpretationInfo = field(default_factory=InterpretationInfo)
    outputs: OutputsInfo = field(default_factory=OutputsInfo)
    costs_usd: CostsUSD = field(default_factory=CostsUSD)
    disclaimer: str = DEFAULT_DISCLAIMER

    def __post_init__(self) -> None:
        self.validate()

    def validate(self) -> None:
        """Validate format constraints and safety invariants.

        Enforces:
        When verdict.level is 'failed', measurement.dominant_frequency_hz,
        frequency_ci_hz, and psd are null, and peaks is empty.
        """
        if self.verdict.level == "failed":
            if self.measurement.dominant_frequency_hz is not None:
                raise ValueError(
                    f"Failed scan result must have null measurement.dominant_frequency_hz, "
                    f"got {self.measurement.dominant_frequency_hz}"
                )
            if self.measurement.frequency_ci_hz is not None:
                raise ValueError(
                    f"Failed scan result must have null measurement.frequency_ci_hz, "
                    f"got {self.measurement.frequency_ci_hz}"
                )
            if len(self.measurement.peaks) > 0:
                raise ValueError(
                    f"Failed scan result must have empty measurement.peaks, "
                    f"got {len(self.measurement.peaks)} peak(s)"
                )
            if self.measurement.psd is not None:
                raise ValueError(
                    f"Failed scan result must have null measurement.psd, "
                    f"got {self.measurement.psd}"
                )

    def to_dict(self) -> Dict[str, Any]:
        """Convert result object to dictionary matching shared result format schema."""
        self.validate()
        return asdict(self)

    def to_json(self, indent: Optional[int] = 2) -> str:
        """Serialize result object to JSON string matching shared result format schema."""
        self.validate()
        return json.dumps(self.to_dict(), indent=indent)

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> ScanResult:
        """Reconstruct ScanResult instance from dictionary."""
        d = dict(data)

        # Verdict
        verdict_val = d.get("verdict", {})
        if isinstance(verdict_val, dict):
            verdict = Verdict(
                level=verdict_val.get("level", "usable"),
                reasons=list(verdict_val.get("reasons", [])),
            )
        elif isinstance(verdict_val, Verdict):
            verdict = verdict_val
        else:
            verdict = Verdict(level=str(verdict_val))

        # Location
        loc_val = d.get("location", {})
        if isinstance(loc_val, dict):
            location = Location(
                lat=float(loc_val.get("lat", 0.0)),
                lon=float(loc_val.get("lon", 0.0)),
            )
        elif isinstance(loc_val, Location):
            location = loc_val
        else:
            location = Location()

        # Video
        v_val = d.get("video", {})
        if isinstance(v_val, dict):
            video = VideoInfo(
                filename=str(v_val.get("filename", "")),
                fps=float(v_val.get("fps", 0.0)),
                duration_s=float(v_val.get("duration_s", 0.0)),
                width=int(v_val.get("width", 0)),
                height=int(v_val.get("height", 0)),
                frame_count=int(v_val.get("frame_count", 0)),
            )
        elif isinstance(v_val, VideoInfo):
            video = v_val
        else:
            video = VideoInfo()

        # Segmentation
        seg_val = d.get("segmentation", {})
        if isinstance(seg_val, dict):
            bg_p = seg_val.get("background_persistence")
            segmentation = SegmentationInfo(
                target_prompt=str(seg_val.get("target_prompt", "concrete pillar")),
                background_prompt=str(seg_val.get("background_prompt", "building")),
                target_source=str(seg_val.get("target_source", "sam")),
                background_source=str(seg_val.get("background_source", "sam")),
                target_persistence=float(seg_val.get("target_persistence", 1.0)),
                background_persistence=float(bg_p) if bg_p is not None else None,
                warnings=list(seg_val.get("warnings", [])),
            )
        elif isinstance(seg_val, SegmentationInfo):
            segmentation = seg_val
        else:
            segmentation = SegmentationInfo()

        # Measurement
        meas_val = d.get("measurement", {})
        if isinstance(meas_val, dict):
            raw_peaks = meas_val.get("peaks", [])
            peaks_list: List[MeasurementPeak] = []
            for p in raw_peaks:
                if isinstance(p, dict):
                    peaks_list.append(
                        MeasurementPeak(
                            frequency_hz=float(p.get("frequency_hz", 0.0)),
                            relative_power=float(p.get("relative_power", 0.0)),
                            snr_db=float(p.get("snr_db", 0.0)),
                        )
                    )
                elif isinstance(p, MeasurementPeak):
                    peaks_list.append(p)

            ci_val = meas_val.get("frequency_ci_hz")
            ci_list = [float(x) for x in ci_val] if ci_val is not None else None
            dom_f = meas_val.get("dominant_frequency_hz")

            # PSD Data
            psd_val = meas_val.get("psd")
            psd_obj: Optional[PSDData] = None
            if isinstance(psd_val, dict):
                psd_obj = PSDData(
                    freq_hz=[float(x) for x in psd_val.get("freq_hz", [])],
                    power=[float(x) for x in psd_val.get("power", [])],
                )
            elif isinstance(psd_val, PSDData):
                psd_obj = psd_val

            measurement = MeasurementInfo(
                units=str(meas_val.get("units", "px")),
                scale=float(meas_val["scale"]) if meas_val.get("scale") is not None else None,
                dominant_frequency_hz=float(dom_f) if dom_f is not None else None,
                frequency_ci_hz=ci_list,
                peaks=peaks_list,
                psd=psd_obj,
                background_residual_px=float(meas_val.get("background_residual_px", 0.0)),
            )
        elif isinstance(meas_val, MeasurementInfo):
            measurement = meas_val
        else:
            measurement = MeasurementInfo()

        # Interpretation
        interp_val = d.get("interpretation", {})
        if isinstance(interp_val, dict):
            qg_val = interp_val.get("quality_gate", {})
            if isinstance(qg_val, dict):
                quality_gate = QualityGateInfo(
                    is_structural_element=bool(qg_val.get("is_structural_element", True)),
                    has_static_background=bool(qg_val.get("has_static_background", True)),
                    appears_stable=bool(qg_val.get("appears_stable", True)),
                    issues=list(qg_val.get("issues", [])),
                )
            elif isinstance(qg_val, QualityGateInfo):
                quality_gate = qg_val
            else:
                quality_gate = QualityGateInfo()

            ass_val = interp_val.get("assessment", {})
            if isinstance(ass_val, dict):
                exp_range = ass_val.get("expected_range_hz")
                assessment = AssessmentInfo(
                    severity=str(ass_val.get("severity", "none")),
                    reasons=list(ass_val.get("reasons", [])),
                    expected_range_hz=[float(x) for x in exp_range] if exp_range is not None else None,
                    confidence=str(ass_val.get("confidence", "low")),
                    recommended_action=str(ass_val.get("recommended_action", "")),
                    assessor=str(ass_val.get("assessor", "local_rules")),
                )
            elif isinstance(ass_val, AssessmentInfo):
                assessment = ass_val
            else:
                assessment = AssessmentInfo()

            interpretation = InterpretationInfo(
                bridge=interp_val.get("bridge"),
                bridge_warning=interp_val.get("bridge_warning"),
                quality_gate=quality_gate,
                assessment=assessment,
            )
        elif isinstance(interp_val, InterpretationInfo):
            interpretation = interp_val
        else:
            interpretation = InterpretationInfo()

        # Outputs
        out_val = d.get("outputs", {})
        if isinstance(out_val, dict):
            outputs = OutputsInfo(
                magnified_video=out_val.get("magnified_video"),
                spectrum_plot=out_val.get("spectrum_plot"),
                displacement_plot=out_val.get("displacement_plot"),
            )
        elif isinstance(out_val, OutputsInfo):
            outputs = out_val
        else:
            outputs = OutputsInfo()

        # Costs USD
        cost_val = d.get("costs_usd", {})
        if isinstance(cost_val, dict):
            costs_usd = CostsUSD(
                sam=float(cost_val.get("sam", 0.0)),
                muse_spark=float(cost_val.get("muse_spark", 0.0)),
                total=float(cost_val.get("total", 0.0)),
            )
        elif isinstance(cost_val, CostsUSD):
            costs_usd = cost_val
        else:
            costs_usd = CostsUSD()

        return cls(
            schema_version=str(d.get("schema_version", "1.0")),
            scan_id=str(d.get("scan_id", "")),
            is_demo=bool(d.get("is_demo", False)),
            created_at=str(d.get("created_at", "")),
            status=d.get("status", "complete"),
            verdict=verdict,
            location=location,
            video=video,
            segmentation=segmentation,
            measurement=measurement,
            interpretation=interpretation,
            outputs=outputs,
            costs_usd=costs_usd,
            disclaimer=str(d.get("disclaimer", DEFAULT_DISCLAIMER)),
        )

    @classmethod
    def from_json(cls, json_str_or_bytes: Union[str, bytes]) -> ScanResult:
        """Parse ScanResult directly from a JSON string or bytes."""
        data = json.loads(json_str_or_bytes)
        return cls.from_dict(data)
